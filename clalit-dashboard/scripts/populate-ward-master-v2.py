def build_rows():
    """Build all ward_master rows."""
    rows = []
    for hosp_code, hosp in HOSPITALS.items():
        for idx, (ward_name, specialty, beds) in enumerate(hosp["wards"], 1):
            ward_code = f"{hosp_code}-{idx:03d}"
            rows.append([
                ward_code,
                ward_name,
                hosp["hospital_field"],
                specialty,
                str(beds),
                "",  # manager (empty for now)
                "TRUE",
            ])
    return rows

def main():
    rows = build_rows()
    print(f"Total wards to write: {len(rows)}")

    # Step 1: Clear all existing data (rows 1 to 500 to be safe)
    print("Clearing existing data...")
    try:
        call_tool("google_sheets__pipedream", "google_sheets-clear-rows", {
            "sheetId": SHEET_ID,
            "worksheetId": WORKSHEET_ID,
            "startIndex": 1,
            "endIndex": 500,
        })
        print("  Cleared rows 1-500")
    except Exception as e:
        print(f"  Warning clearing: {e}")

    # Step 2: Write header
    header = ["ward_code", "ward_name", "hospital", "specialty", "total_beds", "manager", "active"]
    call_tool("google_sheets__pipedream", "google_sheets-add-single-row", {
        "sheetId": SHEET_ID,
        "worksheetId": WORKSHEET_ID,
        "hasHeaders": False,
        "cells": header,
    })
    print("Header written")

    # Step 3: Write all ward rows
    success = 0
    errors = 0
    for i, row in enumerate(rows):
        try:
            call_tool("google_sheets__pipedream", "google_sheets-add-single-row", {
                "sheetId": SHEET_ID,
                "worksheetId": WORKSHEET_ID,
                "hasHeaders": True,
                "cells": row,
            })
            success += 1
            if (i + 1) % 50 == 0:
                print(f"  Written {i + 1}/{len(rows)} rows...")
        except Exception as e:
            errors += 1
            print(f"  Error on row {i + 1} ({row[0]} - {row[1]}): {e}")
            if errors > 5:
                print("Too many errors, stopping.")
                break

    print(f"\nDone! Written {success}/{len(rows)} ward rows to sheet. Errors: {errors}")

if __name__ == "__main__":
    main()
